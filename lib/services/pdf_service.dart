import 'package:flutter/foundation.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../models/document_model.dart';

class PdfService {
  /// Generates a professional PDF document bytes with full English and Hindi Unicode font support
  static Future<Uint8List> generateDocumentPdf(DocumentModel document) async {
    final pdf = pw.Document();

    // Determine if text contains Hindi / Devanagari characters
    final hasHindi = RegExp(r'[\u0900-\u097F]').hasMatch(document.editedText) ||
        RegExp(r'[\u0900-\u097F]').hasMatch(document.title);

    pw.Font baseFont;
    pw.Font boldFont;

    try {
      if (hasHindi) {
        baseFont = await PdfGoogleFonts.notoSansDevanagariRegular();
        boldFont = await PdfGoogleFonts.notoSansDevanagariBold();
      } else {
        baseFont = await PdfGoogleFonts.interRegular();
        boldFont = await PdfGoogleFonts.interBold();
      }
    } catch (e) {
      debugPrint('[PdfService] Error loading Google Fonts, using fallback: $e');
      baseFont = pw.Font.helvetica();
      boldFont = pw.Font.helveticaBold();
    }

    final pageTheme = pw.PageTheme(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(42),
      theme: pw.ThemeData.withFont(
        base: baseFont,
        bold: boldFont,
      ),
      buildBackground: (context) {
        return pw.FullPage(
          ignoreMargins: true,
          child: pw.Container(
            decoration: const pw.BoxDecoration(color: PdfColors.white),
          ),
        );
      },
    );

    final paragraphs = document.editedText
        .split('\n')
        .where((p) => p.trim().isNotEmpty)
        .toList();

    final wordCount = document.editedText
        .trim()
        .split(RegExp(r'\s+'))
        .where((w) => w.isNotEmpty)
        .length;

    final dateFormatted =
        '${document.createdAt.day.toString().padLeft(2, '0')}/'
        '${document.createdAt.month.toString().padLeft(2, '0')}/'
        '${document.createdAt.year} '
        '${document.createdAt.hour.toString().padLeft(2, '0')}:'
        '${document.createdAt.minute.toString().padLeft(2, '0')}';

    pdf.addPage(
      pw.MultiPage(
        pageTheme: pageTheme,
        header: (context) {
          return pw.Container(
            padding: const pw.EdgeInsets.only(bottom: 12),
            decoration: const pw.BoxDecoration(
              border: pw.Border(
                bottom: pw.BorderSide(color: PdfColors.grey300, width: 1),
              ),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Row(
                  children: [
                    pw.Container(
                      width: 14,
                      height: 14,
                      decoration: const pw.BoxDecoration(
                        color: PdfColor.fromInt(0xFFDF6729), // LIKH Coral
                        borderRadius: pw.BorderRadius.all(pw.Radius.circular(4)),
                      ),
                    ),
                    pw.SizedBox(width: 6),
                    pw.Text(
                      'LIKH AI',
                      style: pw.TextStyle(
                        font: boldFont,
                        fontSize: 12,
                        color: const PdfColor.fromInt(0xFF101D2D), // Obsidian Dark
                      ),
                    ),
                  ],
                ),
                pw.Text(
                  'Your handwriting. Digitized.',
                  style: pw.TextStyle(
                    font: baseFont,
                    fontSize: 9,
                    color: PdfColors.grey600,
                  ),
                ),
              ],
            ),
          );
        },
        footer: (context) {
          return pw.Container(
            padding: const pw.EdgeInsets.only(top: 12),
            decoration: const pw.BoxDecoration(
              border: pw.Border(
                top: pw.BorderSide(color: PdfColors.grey300, width: 1),
              ),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  'Generated by LIKH AI',
                  style: pw.TextStyle(
                    font: baseFont,
                    fontSize: 8,
                    color: PdfColors.grey500,
                  ),
                ),
                pw.Text(
                  'Page ${context.pageNumber} of ${context.pagesCount}',
                  style: pw.TextStyle(
                    font: baseFont,
                    fontSize: 8,
                    color: PdfColors.grey500,
                  ),
                ),
              ],
            ),
          );
        },
        build: (context) {
          return [
            pw.SizedBox(height: 16),
            // Title
            pw.Text(
              document.title,
              style: pw.TextStyle(
                font: boldFont,
                fontSize: 22,
                color: PdfColors.black,
              ),
            ),
            pw.SizedBox(height: 6),
            // Metadata chips
            pw.Row(
              children: [
                pw.Text(
                  'Date: $dateFormatted',
                  style: pw.TextStyle(
                    font: baseFont,
                    fontSize: 9,
                    color: PdfColors.grey700,
                  ),
                ),
                pw.SizedBox(width: 15),
                pw.Text(
                  'Words: $wordCount',
                  style: pw.TextStyle(
                    font: baseFont,
                    fontSize: 9,
                    color: PdfColors.grey700,
                  ),
                ),
                pw.SizedBox(width: 15),
                pw.Text(
                  'Lang: ${document.language.toUpperCase()}',
                  style: pw.TextStyle(
                    font: baseFont,
                    fontSize: 9,
                    color: PdfColors.grey700,
                  ),
                ),
              ],
            ),
            pw.SizedBox(height: 12),
            pw.Divider(color: PdfColors.grey300, thickness: 1),
            pw.SizedBox(height: 16),
            // Paragraphs
            ...paragraphs.map((p) {
              final isBullet =
                  p.startsWith('- ') || p.startsWith('• ') || RegExp(r'^\d+[.)]\s').hasMatch(p);

              return pw.Padding(
                padding: const pw.EdgeInsets.only(bottom: 12),
                child: pw.Text(
                  p,
                  style: pw.TextStyle(
                    font: baseFont,
                    fontSize: isBullet ? 11 : 11.5,
                    lineSpacing: 3.5,
                    color: const PdfColor.fromInt(0xFF1F2937),
                  ),
                ),
              );
            }),
          ];
        },
      ),
    );

    return await pdf.save();
  }

  /// Direct Share PDF
  static Future<void> shareDocumentPdf(DocumentModel document) async {
    final bytes = await generateDocumentPdf(document);
    final fileName = '${document.title.replaceAll(RegExp(r'[^\w\s]+'), '_')}.pdf';
    await Printing.sharePdf(bytes: bytes, filename: fileName);
  }

  /// Print or Save via System Print Dialog
  static Future<void> printDocumentPdf(DocumentModel document) async {
    final bytes = await generateDocumentPdf(document);
    await Printing.layoutPdf(
      onLayout: (_) => bytes,
      name: document.title,
    );
  }
}
